const TABLES: Record<AppLanguage, Dict> = { vi, en };

export type TranslationKey = keyof typeof vi;

export function translate(lang: AppLanguage, key: string, fallback?: string): string {
  return TABLES[lang][key] ?? TABLES.vi[key] ?? fallback ?? key;
}

export function languageLabel(lang: AppLanguage): string {
  return lang === 'en' ? 'English' : 'Tiếng Việt';
}
